
using CoreClassLibrary.Extensions;

namespace CoreClassLibrary.Mathematics.Cryptography.Ciphers.StreamCiphers.Algorithms;

/// <summary>
/// Implements ARC4 cipher algorithm
/// </summary>
/// <remarks>
/// ARC4 (Alleged RC4) is an implementation of RC4 (Rivest’s Cipher version 4), a symmetric stream cipher designed by Ron Rivest in 1987.
/// The cipher started as a proprietary design, that was reverse engineered and anonymously posted on Usenet in 1994. 
/// The company that owns RC4(RSA Data Inc.) never confirmed the correctness of the leaked algorithm.
/// Unlike RC2, the company has never published the full specification of RC4, of whom it still holds the trademark.
/// ARC4 keys can vary in length from 40 to 2048 bits.
/// One problem of ARC4 is that it does not take a nonce or an IV. If it is required to encrypt multiple messages with the same long-term key, 
/// a distinct independent nonce must be created for each message, and a short-term key must be derived from the combination of the long-term key and the nonce. 
/// Due to the weak key scheduling algorithm of RC2, the combination must be carried out with a complex function (e.g. a cryptographic hash) and not by simply concatenating key and nonce.
/// 
/// While remarkable for its simplicity and speed in software, multiple vulnerabilities have been discovered in RC4, rendering it insecure.
/// It is especially vulnerable when the beginning of the output keystream is not discarded, or when nonrandom or related keys are used. 
/// Particularly problematic uses of RC4 have led to very insecure protocols such as WEP.
/// As of 2015, there is speculation that some state cryptologic agencies may possess the capability to break RC4 when used in the TLS protocol.
/// IETF has published RFC 7465 to prohibit the use of RC4 in TLS; Mozilla and Microsoft have issued similar recommendations.
/// A number of attempts have been made to strengthen RC4, notably Spritz, RC4A, VMPC, and RC4+
/// </remarks>
/// <see cref="https://en.wikipedia.org/wiki/RC4"/>
public sealed class Arc4Cipher(byte[] key, bool dischargeFirstBytes = true) : XorCipherBase(new Arc4ByteProvider(key, dischargeFirstBytes))
    {
    }

public sealed class Arc4Engine(byte[] key, bool dischargeFirstBytes = true) : XorEngineBase(new Arc4ByteProvider(key, dischargeFirstBytes))
    {
    }

public sealed class Arc4ByteProvider : CipherBase, ISampleProvider<byte>
    {
    private readonly byte[] s = new byte[byte.MaxValue + 1];

    private int x, y;

    //   The first 1536 bytes of keystream
    //   generated by the cipher MUST be discarded, and the first byte of the
    //   first encrypted packet MUST be encrypted using the 1537th byte of
    //   keystream.
    private readonly bool dischargeFirstBytes;

    /// <summary>
    /// Initializes a new instance of the <see cref="Arc4Cipher" /> class.
    /// </summary>
    /// <param name="key">The key.</param>
    /// <param name="dischargeFirstBytes">if set to <c>true</c> will disharged first 1536 bytes.</param>
    public Arc4ByteProvider(byte[] key, bool dischargeFirstBytes = true) : base(key)
        {
        this.dischargeFirstBytes = dischargeFirstBytes;
        this.Initialize();
        }
    
    public override void Initialize()
        {
        this.x = this.y = 0;

        // The array "S" is initialized to the identity permutation
        for (int i = 0; i < this.s.Length; i++)
            {
            this.s[i] = (byte)i;
            }

        int j = 0;
        for (int i = 0; i < this.s.Length; i++)
            {
            j = (j + this.s[i] + this.key[i % this.key.Length]) & 0xff;       // & 0xff => % 256

            this.SwapS(i, j);
            }

        if (this.dischargeFirstBytes)
            {
            EnumerableExtensions.Repeat(this.GetNext, 1536);                
            }
        }

    public byte GetNext()
        {
        // & 0xff => % 256
        this.x = (this.x + 1) & 0xff;
        this.y = (this.y + this.s[this.x]) & 0xff;

        this.SwapS(this.x, this.y);

        return this.s[(this.s[this.x] + this.s[this.y]) & 0xff];
        }

    private void SwapS(int i1, int i2)
        => ObjectExtensions.Swap(ref this.s[i1], ref this.s[i2]);        
    }
